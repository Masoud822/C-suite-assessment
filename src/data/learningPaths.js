// Helper to look up entry by scaled score out of 40
export const getFrameworkEntryByScore = (scoreOutOf40) => {
  const roundedScore = Math.max(0, Math.min(40, Math.round(scoreOutOf40)));
  const found = CEFR_FRAMEWORK.find(entry => roundedScore >= entry.minScore && roundedScore <= entry.maxScore);
  return found || CEFR_FRAMEWORK[0];
};

// Helper to look up entry by level name
export const getFrameworkEntryByLevel = (levelStr) => {
  if (!levelStr) return CEFR_FRAMEWORK[0];
  const clean = levelStr.replace('−', '-').trim().toUpperCase();
  const found = CEFR_FRAMEWORK.find(entry => 
    entry.level.toUpperCase() === levelStr.toUpperCase() || 
    entry.altLevel.toUpperCase() === clean
  );
  return found || CEFR_FRAMEWORK[0];
};

// Map for quick learning path lookup
export const CEFR_LEARNING_PATHS = CEFR_FRAMEWORK.reduce((acc, entry) => {
  acc[entry.level] = entry.learningPath;
  acc[entry.altLevel] = entry.learningPath;
  return acc;
}, {});
